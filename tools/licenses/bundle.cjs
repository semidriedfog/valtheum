// Build a deduplicated, offline-readable catalog for all shipped executables.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'../..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const manifest=JSON.parse(read('licenses/rust/manifest.json'));
const {target,appMetadata,selectPackages}=require('./distribution.cjs');
const selected=selectPackages(appMetadata());
const texts={},components=[];
function add(name,version,license,scope,files){
 const notices=files.map(file=>{const text=read(file);const id=crypto.createHash('sha256').update(text).digest('hex');texts[id]=text;return {file,text:id};});
 components.push({name,version,license,scope,notices});
}
const version=read('Cargo.toml').match(/^version\s*=\s*"([^"]+)"/m)[1];
add('valtheum',version,'MIT','project',['LICENSE']);
add('Third-party notices','','See component licenses','project',['THIRD_PARTY_NOTICES.md']);
add('PDF.js local changes','','Apache-2.0','pdf',['docs/VENDOR_PATCHES.md']);
for(const [key,p]of selected){
 const record=manifest.packages.find(r=>r.name===p.name&&r.version===p.version);
 if(!record||record.license!==p.license)throw Error('Refresh Rust license inventory: '+key);
 add(record.name,record.version,record.license,p.scope,record.notices.map(n=>'licenses/rust/'+n.path));
}
// Show the native database separately from its MIT-licensed Rust wrapper.
const sqlite=manifest.packages.find(p=>p.name==='libsqlite3-sys'&&selected.has(p.name+'-'+p.version));
const sqlcipherLicense=sqlite?.notices.find(n=>n.path.endsWith('/sqlcipher/LICENSE'));
if(!sqlcipherLicense)throw Error('Missing native SQLCipher license');
add('SQLCipher','','BSD-3-Clause','native',['licenses/rust/'+sqlcipherLicense.path]);
// This build dependency supplies native code linked into SQLCipher. Its Rust
// build wrapper and bundled Perl tooling are not shipped native components.
const openssl=manifest.packages.find(p=>p.name==='openssl-src'&&p.scopes.includes('app'));
if(!openssl)throw Error('Missing OpenSSL notice provenance');
const opensslLicense=openssl.notices.find(n=>n.path.endsWith('/openssl/LICENSE.txt'));
if(!opensslLicense)throw Error('Missing native OpenSSL license');
add('OpenSSL',openssl.version.split('+')[1],'Apache-2.0','native',['licenses/rust/'+opensslLicense.path]);
const vendor='static/vendor/pdfjs/';
for(const [name,license,file]of [
 ['PDF.js','Apache-2.0','LICENSE'],
 ['Adobe CMaps','Adobe redistribution terms','cmaps/LICENSE'],
 ['Foxit / PDFium fonts','BSD-style','standard_fonts/LICENSE_FOXIT'],
 ['Liberation fonts','GPL v2 with the bundled exceptions','standard_fonts/LICENSE_LIBERATION'],
 ['ICC profiles','CC0-1.0','iccs/LICENSE'],
 ['OpenJPEG','BSD-style','wasm/LICENSE_OPENJPEG'],
 ['PDF.js OpenJPEG integration','BSD-style','wasm/LICENSE_PDFJS_OPENJPEG'],
 ['JBIG2 / PDFium','BSD-style','wasm/LICENSE_JBIG2'],
 ['PDF.js JBIG2 integration','BSD-style','wasm/LICENSE_PDFJS_JBIG2'],
 ['qcms','MIT-style','wasm/LICENSE_QCMS'],
 ['PDF.js qcms integration','BSD-style','wasm/LICENSE_PDFJS_QCMS']
])add(name,name==='PDF.js'?'6.3.289':name==='Liberation fonts'?'1.07.4':'',license,'pdf',name==='Liberation fonts'?[vendor+file,'licenses/sources/README.md','licenses/sources/liberation-fonts-1.07.4.json']:[vendor+file]);
const fontSource=JSON.parse(read('licenses/sources/liberation-fonts-1.07.4.json')).source.file;
const files=[...new Set([...components.flatMap(c=>c.notices.map(n=>n.file)),fontSource,
 'licenses/DISTRIBUTION.md','licenses/distribution.json'])].sort();
for(const file of files){
 if(path.isAbsolute(file)||file.split(/[\\/]/).includes('..'))throw Error('Unsafe distribution notice path: '+file);
}
fs.writeFileSync(path.join(root,'licenses/distribution.json'),JSON.stringify({target,components,files},null,2)+'\n');
const labels={project:'Project',app:'Runtime dependency',generated:'Generated code notices',native:'Native library',pdf:'PDF resource'};
let inventory='# Distributed component notices\n\nGenerated by `node tools/licenses/bundle.cjs` for the Windows app and standalone Rust recovery tools. Runtime dependencies follow normal dependency edges of the locked Windows Cargo graph. Build/test-only and benchmark-only dependencies are excluded. Direct procedural-macro notices are retained conservatively for generated app code; their host-only dependencies are excluded. Native OpenSSL is included explicitly. This is a notice inventory, not an exact linker-symbol inventory.\n\nOriginal texts are preserved. The packaged paths are recorded in [distribution.json](distribution.json). Development-only inventories remain in the source repository.\n\n| Component | Version | License | Scope | Notices |\n| --- | --- | --- | --- | --- |\n';
for(const c of components)inventory+='| '+c.name+' | '+c.version+' | '+c.license+' | '+labels[c.scope]+' | '+c.notices.map(n=>'['+path.posix.basename(n.file)+']('+encodeURI(path.posix.relative('licenses',n.file))+')').join(', ')+' |\n';
fs.writeFileSync(path.join(root,'licenses/DISTRIBUTION.md'),inventory);
const result={version,summary:read('THIRD_PARTY_NOTICES.md'),patches:read('docs/VENDOR_PATCHES.md'),components,texts};
const serialized=JSON.stringify(result).replaceAll('<','\\u003c');
fs.writeFileSync(path.join(root,'static/licenses.json'),serialized+'\n');
console.log(components.length+' components, '+Object.keys(texts).length+' distinct texts, '+Buffer.byteLength(serialized)+' bytes');
