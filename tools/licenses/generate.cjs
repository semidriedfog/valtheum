// Rebuild Rust notices from locked, locally cached Cargo sources.
const fs = require('node:fs');
const path = require('node:path');
const cp = require('node:child_process');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '../..');
const output = path.join(root, 'licenses/rust');
const target = 'x86_64-pc-windows-msvc';
const projects = [
    ['app', 'Cargo.toml'],
    ['archive benchmark', 'tools/archive-crypto-bench/Cargo.toml'],
    ['video benchmark', 'tools/video-crypto-bench/Cargo.toml']
];
const packages = new Map();
for (const [scope, manifest] of projects) {
    const metadata = JSON.parse(cp.execFileSync('cargo', ['metadata', '--locked', '--offline',
        '--format-version', '1', '--filter-platform', target, '--manifest-path', manifest],
        {cwd: root, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024}));
    const resolved = new Set(metadata.resolve.nodes.map(node => node.id));
    for (const item of metadata.packages) {
        if (!item.source || !resolved.has(item.id)) continue;
        const key = item.name + '-' + item.version;
        if (!packages.has(key)) packages.set(key, {item, scopes: new Set()});
        packages.get(key).scopes.add(scope);
    }
}
function licenseFiles(directory) {
    const found = [];
    function walk(folder, inLicenseDirectory = false) {
        for (const entry of fs.readdirSync(folder, {withFileTypes: true})) {
            const file = path.join(folder, entry.name);
            if (entry.isDirectory()) {
                if (!['.git', 'target'].includes(entry.name))
                    walk(file, inLicenseDirectory || /^(licenses?|licences?)$/i.test(entry.name));
            } else if (entry.isFile() &&
                (inLicenseDirectory || /^(licen[cs]e|copying|notice|copyright|authors)([._-]|$)/i.test(entry.name)) &&
                !/\.(rs|c|h|py|pm|sh|html)$/i.test(entry.name)) {
                found.push(file);
            }
        }
    }
    walk(directory);
    return found;
}
const records = [];
for (const [key, {item, scopes}] of [...packages].sort(([a], [b]) => a.localeCompare(b, 'en'))) {
    const base = path.dirname(item.manifest_path);
    let files = licenseFiles(base).map(file => ({file, relative: path.relative(base, file)}));
    if (item.license_file) {
        const file = path.resolve(base, item.license_file);
        if (!files.some(x => x.file === file) && fs.existsSync(file))
            files.push({file, relative: path.basename(file)});
    }
    if (!files.length) {
        const fallback = path.join(root, 'licenses/upstream', key);
        if (fs.existsSync(fallback))
            files = licenseFiles(fallback).map(file => ({file, relative: path.relative(fallback, file)}));
    }
    if (!files.length || !item.license) throw new Error('Missing license information: ' + key);
    const notices = [];
    for (const {file, relative} of files.sort((a, b) => a.relative.localeCompare(b.relative, 'en'))) {
        const destination = path.resolve(output, key, relative);
        if (!destination.startsWith(path.resolve(output, key) + path.sep))
            throw new Error('Unsafe license path: ' + relative);
        fs.mkdirSync(path.dirname(destination), {recursive: true});
        const bytes = fs.readFileSync(file);
        fs.writeFileSync(destination, bytes);
        notices.push({path: path.relative(output, destination).split(path.sep).join('/'),
            sha256: crypto.createHash('sha256').update(bytes).digest('hex')});
    }
    records.push({name: item.name, version: item.version, license: item.license,
        repository: item.repository, source: 'https://crates.io/crates/' + item.name + '/' + item.version,
        scopes: [...scopes], notices});
}
fs.mkdirSync(output, {recursive: true});
fs.writeFileSync(path.join(output, 'manifest.json'), JSON.stringify({target, packages: records}, null, 2) + '\n');
let markdown = '# Rust dependency licenses\n\nGenerated by node tools/licenses/generate.cjs from the three committed Cargo lockfiles for ' + target + '.\n\n'
    + 'This includes resolved runtime, build, and test dependencies; it is not a claim that every package is linked into every executable. Benchmark-only packages are identified in the Scope column. License expressions are copied from package metadata, without choosing an alternative or relicensing upstream code. Original notices, including nested native-library notices, are copied without editing. Exact file hashes are in [manifest.json](manifest.json).\n\n'
    + 'Crates missing license texts in their published archive use the version-specific copies under [upstream](../upstream), with provenance in [upstream-sources.json](../upstream-sources.json). This full inventory stays in the source repository. Binary distributions use the selected [distribution inventory](../DISTRIBUTION.md); development-only tools are documented in [development licenses](../../docs/DEVELOPMENT_LICENSES.md).\n\n'
    + '| Package | Version | Declared license | Scope | Original notices |\n| --- | --- | --- | --- | --- |\n';
for (const record of records) {
    markdown += '| [' + record.name + '](' + record.source + ') | ' + record.version + ' | '
        + record.license + ' | ' + record.scopes.join(', ') + ' | '
        + record.notices.map(n => '[' + n.path.slice(n.path.indexOf('/') + 1) + '](' + encodeURI(n.path) + ')').join(', ')
        + ' |\n';
}
fs.writeFileSync(path.join(output, 'README.md'), markdown);
console.log(records.length + ' Rust dependency versions; ' +
    records.reduce((count, record) => count + record.notices.length, 0) + ' original notice files.');

require('./bundle.cjs');
